/** Translate one piece of interface text; text without a translation is returned unchanged. */
export function trS(s: string): string {
  if (!s) return s;
  const v = AR[s] ?? EXTRA[s];
  if (v != null) return v;
  if (s.includes('\n')) return s.split('\n').map(trS).join('\n');
  for (const [re, f] of [...EXTRA_PATTERNS, ...AR_PATTERNS]) {
    const m = re.exec(s);
    if (m) return f(m);
  }
  let m: RegExpExecArray | null;
  if ((m = /^(.+?) ?▶$/.exec(s))) { const a = trS(m[1]); if (a !== m[1]) return a + ' ◀'; }
  if ((m = /^(\d+) · (.+)$/.exec(s))) { const a = trS(m[2]); if (a !== m[2]) return m[1] + ' · ' + a; }
  if ((m = /^(.+) \((\d+)\)$/.exec(s))) { const a = trS(m[1]); if (a !== m[1]) return a + ' (' + m[2] + ')'; }
  const c = s.indexOf(': ');
  if (c > 0) { const a = s.slice(0, c), b = s.slice(c + 2), ta = trS(a), tb = trS(b); if (ta !== a || tb !== b) return ta + ': ' + tb; }
  for (const sep of [' · ', ' – ', ', ']) {
    if (s.includes(sep)) { const p = s.split(sep), t = p.map(trS); if (t.some((x, i) => x !== p[i])) return t.join(sep === ', ' ? '، ' : sep); }
  }
  return s;
}

/** Translate text, keeping its leading and trailing spaces; arrows turn for right-to-left reading. */
export function trText(v: string): string {
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(v) as RegExpExecArray;
  // Text written across several lines in JSX keeps its indentation: read it as one line.
  const core = /\n[ \t]{2,}/.test(m[2]) ? m[2].replace(/\s+/g, ' ') : m[2];
  const t = trS(core);
  return t === core ? v.replace(/→/g, '←') : m[1] + t.replace(/→/g, '←') + m[3];
}

